'use strict';
// Status line: `creative ▓▓▓▓░ 64% · resets Mon`
//
// Plugins can't register a status line themselves, so `tokenjar statusline
// install` points settings.json at a small, stable shim in the tokenjar
// config dir. The shim forwards to the currently installed plugin version
// (the SessionStart hook keeps that path current, since the plugin's own
// directory changes on every update). An existing status line is preserved
// and chained: its output is shown first, then the tokenjar segment.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const paths = require('./paths');
const fsu = require('./fsutil');
const log = require('./log');

const PLUGIN_ROOT = path.resolve(__dirname, '..');

function shimFile() {
  return path.join(paths.configDir(), 'statusline.js');
}

function chainFile() {
  return path.join(paths.configDir(), 'statusline-chain.json');
}

function settingsFile() {
  return path.join(paths.claudeDir(), 'settings.json');
}

function shimSource(root) {
  return [
    '// Generated by tokenjar. Forwards to the installed plugin version; rewritten',
    '// automatically when the plugin updates. Safe to delete (run',
    '// `/budget statusline uninstall` to also remove it from settings.json).',
    "'use strict';",
    `const root = ${JSON.stringify(root)};`,
    "const entry = require('path').join(root, 'scripts', 'tokenjar.js');",
    "if (require('fs').existsSync(entry)) {",
    "  process.argv = [process.argv[0], entry, 'statusline'];",
    '  require(entry);',
    '}',
    '',
  ].join('\n');
}

/** Called from SessionStart: keep the shim pointing at this plugin version. */
function refreshShim() {
  const file = shimFile();
  if (!fs.existsSync(file)) return false; // status line not installed
  const want = shimSource(PLUGIN_ROOT);
  let have = '';
  try { have = fs.readFileSync(file, 'utf8'); } catch { /* rewrite */ }
  if (have === want) return false;
  fs.writeFileSync(file, want);
  return true;
}

/**
 * A stable launcher at <config>/cli.js that forwards to the installed plugin
 * version, for tools outside the plugin (the tokenjar pane) that can't know
 * where the plugin lives. Kept current on every SessionStart.
 */
function cliShimFile() {
  return path.join(paths.configDir(), 'cli.js');
}

function cliShimSource(root) {
  return [
    '// Generated by tokenjar on every session start: forwards to the installed',
    '// plugin version, for the tokenjar pane. Safe to delete.',
    "'use strict';",
    `const root = ${JSON.stringify(root)};`,
    "const entry = require('path').join(root, 'scripts', 'tokenjar.js');",
    "if (require('fs').existsSync(entry)) {",
    '  process.argv = [process.argv[0], entry, ...process.argv.slice(2)];',
    '  require(entry);',
    '} else {',
    "  process.stdout.write(JSON.stringify({ error: 'tokenjar plugin not found at ' + root + '; start a new Claude Code session to refresh' }) + '\\n');",
    '}',
    '',
  ].join('\n');
}

function refreshCliShim() {
  const file = cliShimFile();
  const want = cliShimSource(PLUGIN_ROOT);
  let have = '';
  try { have = fs.readFileSync(file, 'utf8'); } catch { /* write */ }
  if (have === want) return false;
  fsu.ensureDir(path.dirname(file));
  fs.writeFileSync(file, want);
  return true;
}

function shimCommand() {
  return `node "${paths.toSlash(shimFile())}"`;
}

function isOurs(statusLine) {
  if (!statusLine || typeof statusLine.command !== 'string') return false;
  const cmd = paths.toSlash(statusLine.command).toLowerCase();
  return cmd.includes(paths.toSlash(shimFile()).toLowerCase()) || /tokenjar[\\/]+(statusline|scripts[\\/]+tokenjar)\.js/.test(cmd);
}

function readSettings() {
  const file = settingsFile();
  if (!fs.existsSync(file)) return { file, settings: {} };
  const raw = fs.readFileSync(file, 'utf8');
  try {
    return { file, settings: raw.trim() ? JSON.parse(raw) : {} };
  } catch {
    throw new Error(`${file} is not valid JSON; not touching it. Fix it or add the status line by hand: ${shimCommand()}`);
  }
}

function writeSettings(file, settings) {
  if (fs.existsSync(file)) fs.copyFileSync(file, `${file}.tokenjar-backup`);
  fsu.ensureDir(path.dirname(file));
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(settings, null, 2) + '\n');
  fs.renameSync(tmp, file);
}

function install({ force = false } = {}) {
  const { file, settings } = readSettings();
  const lines = [];
  fsu.ensureDir(paths.configDir());
  fs.writeFileSync(shimFile(), shimSource(PLUGIN_ROOT));
  const existing = settings.statusLine;
  if (existing && !isOurs(existing)) {
    if (force) {
      lines.push('Replaced your existing status line (backup in settings.json.tokenjar-backup).');
      try { fs.unlinkSync(chainFile()); } catch { /* none */ }
    } else {
      fs.writeFileSync(chainFile(), JSON.stringify(existing, null, 2));
      lines.push('Kept your existing status line: its output is shown first, then the tokenjar segment.');
    }
  }
  const next = { type: 'command', command: shimCommand() };
  if (existing && typeof existing.padding === 'number') next.padding = existing.padding;
  if (existing && typeof existing.refreshInterval === 'number') next.refreshInterval = existing.refreshInterval;
  settings.statusLine = next;
  writeSettings(file, settings);
  lines.unshift(`Status line installed in ${file}.`);
  lines.push('It appears after the next message (or restart Claude Code).');
  return lines.join('\n');
}

function uninstall() {
  const { file, settings } = readSettings();
  const chained = fsu.readJson(chainFile(), null);
  if (isOurs(settings.statusLine)) {
    if (chained) settings.statusLine = chained;
    else delete settings.statusLine;
    writeSettings(file, settings);
  }
  for (const f of [chainFile(), shimFile()]) {
    try { fs.unlinkSync(f); } catch { /* already gone */ }
  }
  return chained ? `Status line removed; your previous status line was restored in ${file}.` : `Status line removed from ${file}.`;
}

// ----- rendering -------------------------------------------------------------

function bashPath() {
  if (process.env.CLAUDE_CODE_GIT_BASH_PATH && fs.existsSync(process.env.CLAUDE_CODE_GIT_BASH_PATH)) return process.env.CLAUDE_CODE_GIT_BASH_PATH;
  for (const p of ['C:\\Program Files\\Git\\bin\\bash.exe', 'C:\\Program Files (x86)\\Git\\bin\\bash.exe']) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

/** Run the user's previous status line command with the same stdin, like Claude Code would. */
function runChained(rawInput) {
  const chained = fsu.readJson(chainFile(), null);
  if (!chained || typeof chained.command !== 'string' || !chained.command.trim()) return '';
  let cmd;
  let args;
  if (process.platform === 'win32') {
    const bash = bashPath();
    if (bash) [cmd, args] = [bash, ['-c', chained.command]];
    else [cmd, args] = ['powershell.exe', ['-NoProfile', '-Command', chained.command]];
  } else {
    [cmd, args] = ['/bin/sh', ['-c', chained.command]];
  }
  const r = spawnSync(cmd, args, { input: rawInput, encoding: 'utf8', timeout: 3000, windowsHide: true });
  if (r.error) {
    log.warn('chained status line failed', r.error);
    return '';
  }
  return (r.stdout || '').replace(/\s+$/, '');
}

const COLORS = { green: '\x1b[32m', yellow: '\x1b[33m', red: '\x1b[31m', dim: '\x1b[2m', reset: '\x1b[0m' };

function colorize(text, color, enabled) {
  return enabled && color ? `${COLORS[color]}${text}${COLORS.reset}` : text;
}

/** Combine the chained output and our segment. */
function combine(theirs, ours) {
  if (!theirs) return ours;
  if (!ours) return theirs;
  const lines = theirs.split('\n');
  if (lines.length === 1) return `${theirs}  ${ours}`;
  return `${theirs}\n${ours}`;
}

module.exports = {
  install,
  uninstall,
  refreshShim,
  refreshCliShim,
  cliShimFile,
  cliShimSource,
  runChained,
  combine,
  colorize,
  shimFile,
  chainFile,
  settingsFile,
  shimSource,
  PLUGIN_ROOT,
};
